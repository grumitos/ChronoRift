const MESSAGES: Record<Language, Record<MessageKey, string>> = { es, en };

let current: Language = systemLanguageGuess();

/** Idioma del sistema según el visor, para lo que se pinta antes de leer la configuración. */
export function systemLanguageGuess(): Language {
  const system = typeof navigator === "undefined" ? "" : navigator.language ?? "";
  return /^es(?:-|$)/i.test(system) ? "es" : "en";
}

export function currentLanguage() {
  return current;
}

/** Cambia el idioma de los textos y de los formatos; quien llama vuelve a pintar. */
export function setLanguage(language: Language) {
  current = language;
  if (typeof document !== "undefined") document.documentElement.lang = language;
}

/** Texto de la clave en el idioma actual, con `{nombre}` reemplazado por cada parámetro. */
export function t(key: MessageKey, params: Record<string, string | number> = {}) {
  const template = MESSAGES[current][key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

/** Singular o plural según la cantidad; la cantidad va en `{count}` ya formateada. */
export function plural(count: number, one: MessageKey, other: MessageKey, formatted: string = String(count)) {
  return t(count === 1 ? one : other, { count: formatted });
}

/**
 * Locale de Intl para números y fechas: el genérico de cada idioma, sin la variante regional del
 * sistema, así los formatos siguen al idioma elegido: "24,5 MiB" y "20 sept 2025, 0:01" en
 * español, "24.5 MiB" y "Sep 20, 2025, 12:01 AM" en inglés.
 */
export function formatLocale() {
  return current === "es" ? "es" : "en-US";
}

/**
 * Reescribe los textos fijos del HTML: `data-i18n` (contenido), `data-i18n-aria` (aria-label),
 * `data-i18n-title` (title) y `data-i18n-placeholder`. Un botón con icono lleva el texto en su
 * propio `<span data-i18n>` para no borrar el icono.
 */
export function translateStatic(root: ParentNode = document) {
  for (const node of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    const text = t(node.dataset.i18n as MessageKey);
    if (node.textContent !== text) node.textContent = text;
  }
  for (const [attribute, name] of [
    ["i18nAria", "aria-label"],
    ["i18nTitle", "title"],
    ["i18nPlaceholder", "placeholder"],
  ] as const) {
    const selector = `[data-${attribute.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}]`;
    for (const node of root.querySelectorAll<HTMLElement>(selector)) {
      node.setAttribute(name, t(node.dataset[attribute] as MessageKey));
    }
  }
}
